import assert from "node:assert/strict";
import { mkdtemp } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { launchScene, visualScenes } from "./electron-harness.mjs";

const directory = await mkdtemp(join(tmpdir(), "ui-kit-pr-ui-"));
for (const width of [1180, 720]) {
  const { app, page } = await launchScene(visualScenes.find(scene => scene.id === "pull-request-detail"), { capture: false });
  try {
    await app.evaluate(({ BrowserWindow, ipcMain }) => {
      BrowserWindow.getAllWindows()[0].setContentSize(1180, 820);
      globalThis.__prCreateCalls = [];
      globalThis.__prReadFails = true;
      globalThis.__prCreated = false;
      globalThis.__prDetailFails = false;
      globalThis.__prEdited = null;
      globalThis.__prEditCalls = [];
      globalThis.__prEditLosesResponse = true;
      globalThis.__prMergeCalls = [];
      globalThis.__prMerged = false;
      globalThis.__prMergeStatusFails = false;
      ipcMain.removeHandler("demo:git:pr-merge");
      ipcMain.removeHandler("demo:git:pr-merge-status");
      ipcMain.handle("demo:git:pr-merge", async (_event, input) => {
        globalThis.__prMergeCalls.push(input);
        await new Promise(resolve => { globalThis.__prMergeRelease = resolve; });
        globalThis.__prMerged = true;
        throw new Error("synthetic merged but reconciliation failed");
      });
      ipcMain.handle("demo:git:pr-merge-status", (_event, input) => {
        if (globalThis.__prMergeStatusFails) throw new Error("synthetic status read failure");
        return { number: input.number, url: "https://github.com/owner/repo/pull/1", state: globalThis.__prMerged ? "MERGED" : "OPEN", head: input.head, branch: "feat/example", baseRefName: "main", baseRefOid: "b".repeat(40), mergeable: "UNKNOWN", mergeCommit: globalThis.__prMerged ? "c".repeat(40) : null };
      });
      ipcMain.removeHandler("demo:git:pr-edit");
      ipcMain.handle("demo:git:pr-edit", (_event, input) => {
        globalThis.__prEditCalls.push(input);
        globalThis.__prEdited = { title: input.title, body: input.body };
        if (globalThis.__prEditLosesResponse) throw new Error("synthetic saved but response lost");
        return { number: 1, url: "https://github.com/owner/repo/pull/1", title: input.title, body: input.body, state: "OPEN", baseRefName: "main", baseRefOid: "b".repeat(40), headRefOid: "a".repeat(40), changedFiles: 3, files: [] };
      });
      globalThis.__prDiffFails = false;
      ipcMain.removeHandler("demo:git:pr-diff");
      ipcMain.handle("demo:git:pr-diff", (_event, input) => {
        if (globalThis.__prDiffFails) throw new Error("synthetic stale diff");
        if (input.number !== 1 || input.head !== "a".repeat(40)) throw new Error("wrong PR revision");
        return { number: 1, head: input.head, patch: "diff --git a/src/example.ts b/src/example.ts\n-previous\n+<script>literal patch</script>\n".repeat(30) };
      });
      ipcMain.removeHandler("demo:git:pr-detail");
      ipcMain.handle("demo:git:pr-detail", () => {
        if (globalThis.__prDetailFails) throw new Error("synthetic detail failure");
        return { number: 1, url: "https://github.com/owner/repo/pull/1", title: "Existing details", body: "<script>not executed</script>\nBody text", state: "OPEN", baseRefName: "main", baseRefOid: "b".repeat(40), headRefOid: "a".repeat(40), changedFiles: 3, files: [{ path: "src/example.ts", additions: 2, deletions: 1 }], ...globalThis.__prEdited };
      });
      ipcMain.removeHandler("demo:git:pr-preview");
      ipcMain.removeHandler("demo:git:pr-create");
      ipcMain.handle("demo:git:pr-preview", () => {
        if (globalThis.__prReadFails) throw new Error("synthetic read failure");
        return { repository: "owner/repo", branch: "feat/example", head: "a".repeat(40), fingerprint: "fresh", pullRequests: globalThis.__prCreated ? [{ number: 1, title: "existing", baseRefName: "main", headRefOid: "a".repeat(40), url: "https://github.com/owner/repo/pull/1" }] : [] };
      });
      ipcMain.handle("demo:git:pr-create", (_event, input) => {
        globalThis.__prCreateCalls.push(input);
        globalThis.__prCreated = true;
        throw new Error("synthetic lost response after creation");
      });
    });
    await app.evaluate(({ BrowserWindow }, width) => BrowserWindow.getAllWindows()[0].setContentSize(width, 820), width);
    await page.getByRole("button", { name: "Live local", exact: true }).click();
    await page.getByRole("button", { name: "Prepare pull request", exact: true }).click();
    const dialog = page.getByRole("dialog", { name: "Prepare pull request", exact: true });
    const confirm = dialog.getByRole("button", { name: "Confirm create PR", exact: true });
    await dialog.getByLabel("PR title", { exact: true }).fill("feat: example");
    await dialog.getByLabel("PR description", { exact: true }).fill("Preserve this draft");
    assert.equal(await confirm.isDisabled(), true);
    await dialog.getByRole("button", { name: "Refresh PRs", exact: true }).click();
    await dialog.getByRole("alert").waitFor();
    assert.equal(await dialog.getByLabel("PR description", { exact: true }).inputValue(), "Preserve this draft");
    await app.evaluate(() => { globalThis.__prReadFails = false; });
    await dialog.getByRole("button", { name: "Refresh PRs", exact: true }).click();
    await dialog.getByText("No open PR for this branch.", { exact: true }).waitFor();
    const bounds = await dialog.boundingBox();
    assert.ok(bounds && bounds.x >= 0 && bounds.x + bounds.width <= width && bounds.y >= 0 && bounds.y + bounds.height <= 820);
    await page.screenshot({ path: join(directory, `preview-${width}.png`) });
    await confirm.click();
    await dialog.getByRole("alert").waitFor();
    assert.equal(await confirm.isDisabled(), true);
    const calls = await app.evaluate(() => globalThis.__prCreateCalls);
    assert.equal(calls.length, 1);
    assert.equal(calls[0].title, "feat: example");
    assert.equal(calls[0].body, "Preserve this draft");
    assert.equal(calls[0].fingerprint, "fresh");
    await dialog.getByRole("button", { name: "Refresh PRs", exact: true }).click();
    await dialog.getByText(/Existing PR #1:/).waitFor();
    assert.equal(await confirm.isDisabled(), true, "Reconciled existing PR prevents blind retry");
    const link = dialog.getByRole("link", { name: "Open PR #1 on GitHub", exact: true });
    assert.equal(await link.getAttribute("href"), "https://github.com/owner/repo/pull/1");
    await dialog.getByRole("button", { name: "Read details #1", exact: true }).click();
    const detail = dialog.getByRole("region", { name: "PR details", exact: true });
    await detail.getByText("1 of 3 changed files shown", { exact: true }).waitFor();
    assert.ok((await detail.textContent()).includes("<script>not executed</script>"));
    assert.equal(await detail.locator("script").count(), 0);
    const detailBounds = await dialog.boundingBox();
    assert.ok(detailBounds && detailBounds.y >= 0 && detailBounds.y + detailBounds.height <= 820);
    const closeBounds = await dialog.getByRole("button", { name: "Close", exact: true }).boundingBox();
    assert.ok(closeBounds && closeBounds.y >= 0 && closeBounds.y + closeBounds.height <= 820, "Footer must remain inside the window");
    await page.screenshot({ path: join(directory, `details-${width}.png`) });
    await detail.getByRole("button", { name: "Read PR diff", exact: true }).click();
    const patch = dialog.getByLabel("PR diff", { exact: true });
    await patch.waitFor();
    assert.ok((await patch.textContent()).includes("+<script>literal patch</script>"));
    assert.equal(await patch.locator("script").count(), 0);
    await patch.scrollIntoViewIfNeeded();
    const diffFooter = await dialog.getByRole("button", { name: "Close", exact: true }).boundingBox();
    assert.ok(diffFooter && diffFooter.y >= 0 && diffFooter.y + diffFooter.height <= 820);
    await page.screenshot({ path: join(directory, `diff-${width}.png`) });
    await app.evaluate(() => { globalThis.__prDiffFails = true; });
    await detail.getByRole("button", { name: "Read PR diff", exact: true }).click();
    await dialog.getByRole("alert").waitFor();
    assert.equal(await patch.count(), 0, "Failed diff refresh must remove the previous patch");
    await app.evaluate(() => { globalThis.__prDiffFails = false; });
    await detail.getByRole("button", { name: "Read PR diff", exact: true }).click();
    await patch.waitFor();
    await app.evaluate(() => { globalThis.__prDetailFails = true; });
    await dialog.getByRole("button", { name: "Read details #1", exact: true }).click();
    await dialog.getByRole("alert").waitFor();
    assert.equal(await detail.count(), 0, "Failed detail refresh must clear obsolete contents");
    assert.equal(await patch.count(), 0);
    await app.evaluate(() => { globalThis.__prDetailFails = false; });
    await dialog.getByRole("button", { name: "Read details #1", exact: true }).click();
    await detail.waitFor();
    await detail.getByRole("button", { name: "Edit title and description", exact: true }).click();
    const editor = dialog.getByRole("region", { name: "Edit existing PR", exact: true });
    const save = editor.getByRole("button", { name: "Confirm update PR", exact: true });
    assert.equal(await save.isDisabled(), true, "Unchanged PR cannot be submitted");
    await editor.getByLabel("Existing PR title", { exact: true }).fill("Edited title");
    await editor.getByLabel("Existing PR description", { exact: true }).fill("Edited description");
    assert.equal((await app.evaluate(() => globalThis.__prEditCalls)).length, 0);
    await editor.scrollIntoViewIfNeeded();
    await page.screenshot({ path: join(directory, `edit-${width}.png`) });
    await save.click();
    await dialog.getByRole("alert").waitFor();
    assert.equal(await save.isDisabled(), true, "Uncertain result requires a fresh detail read");
    assert.equal(await editor.getByLabel("Existing PR description", { exact: true }).inputValue(), "Edited description");
    assert.equal(await detail.count(), 0);
    await dialog.getByRole("button", { name: "Read details #1", exact: true }).click();
    await detail.waitFor();
    assert.equal(await save.isDisabled(), true, "Already-saved edits must not be blindly retried");
    const editCalls = await app.evaluate(() => globalThis.__prEditCalls);
    assert.equal(editCalls.length, 1);
    assert.equal(editCalls[0].expected.title, "Existing details");
    await app.evaluate(() => { globalThis.__prEditLosesResponse = false; });
    await editor.getByLabel("Existing PR title", { exact: true }).fill("Verified edited title");
    await save.click();
    await dialog.getByText("Updated PR #1.", { exact: true }).waitFor();
    assert.equal(await editor.count(), 0);
    assert.ok((await detail.textContent()).includes("Verified edited title"));
    assert.ok((await dialog.getByRole("region", { name: "PR preview", exact: true }).textContent()).includes("Verified edited title"));
    const editedFooter = await dialog.getByRole("button", { name: "Close", exact: true }).boundingBox();
    assert.ok(editedFooter && editedFooter.y >= 0 && editedFooter.y + editedFooter.height <= 820);
    await page.screenshot({ path: join(directory, `edited-${width}.png`) });
    await detail.getByRole("button", { name: "Edit title and description", exact: true }).click();
    await editor.getByLabel("Existing PR title", { exact: true }).fill("Cancelled title");
    await editor.getByRole("button", { name: "Cancel PR edit", exact: true }).click();
    assert.equal((await app.evaluate(() => globalThis.__prEditCalls)).length, 2);
    assert.equal(await dialog.getByLabel("PR description", { exact: true }).inputValue(), "Preserve this draft");
    await dialog.getByRole("button", { name: "Prepare admin squash merge", exact: true }).click();
    const mergePanel = dialog.getByRole("region", { name: "Confirm PR merge", exact: true });
    const merge = mergePanel.getByRole("button", { name: "Confirm admin squash merge", exact: true });
    assert.equal(await merge.isDisabled(), true);
    await mergePanel.getByLabel("Authorize admin merge after local validation", { exact: true }).check();
    await mergePanel.getByLabel("Confirm merge head", { exact: true }).fill("wrong");
    assert.equal(await merge.isDisabled(), true);
    await mergePanel.getByLabel("Confirm merge head", { exact: true }).fill("a".repeat(40));
    assert.equal((await app.evaluate(() => globalThis.__prMergeCalls)).length, 0);
    await mergePanel.scrollIntoViewIfNeeded();
    await page.screenshot({ path: join(directory, `merge-confirm-${width}.png`) });
    await merge.click();
    await dialog.getByText("Merging pull request…", { exact: true }).waitFor();
    assert.equal(await dialog.getByRole("button", { name: "Close", exact: true }).isDisabled(), true);
    await app.evaluate(() => { globalThis.__prMergeRelease(); });
    await mergePanel.getByRole("alert").waitFor();
    assert.equal(await merge.isDisabled(), true, "Uncertain merge must not allow a blind retry");
    const mergeCalls = await app.evaluate(() => globalThis.__prMergeCalls);
    assert.equal(mergeCalls.length, 1);
    assert.equal(mergeCalls[0].head, "a".repeat(40));
    assert.equal(mergeCalls[0].adminConfirmed, true);
    await app.evaluate(() => { globalThis.__prMergeStatusFails = true; });
    await mergePanel.getByRole("button", { name: "Check merge result", exact: true }).click();
    await mergePanel.getByRole("alert").waitFor();
    await app.evaluate(() => { globalThis.__prMergeStatusFails = false; });
    await mergePanel.getByRole("button", { name: "Check merge result", exact: true }).click();
    await mergePanel.getByText(/^Merged PR #1 at/).waitFor();
    assert.equal(await merge.count(), 0);
    assert.equal(await detail.count(), 0);
    assert.equal((await app.evaluate(() => globalThis.__prMergeCalls)).length, 1);
    const mergeFooter = await dialog.getByRole("button", { name: "Close", exact: true }).boundingBox();
    assert.ok(mergeFooter && mergeFooter.y >= 0 && mergeFooter.y + mergeFooter.height <= 820);
    await page.screenshot({ path: join(directory, `merged-${width}.png`) });
    await dialog.getByRole("button", { name: "Close", exact: true }).click();
    await page.waitForFunction(() => document.activeElement?.textContent === "Prepare pull request");
  } finally { await app.close(); }
}
console.log(JSON.stringify({ passed: true, directory, widths: [1180, 720], syntheticIpc: true, realGitHubWrites: 0 }));
